/**
 * Get module-specific pending work notification (10 AM - 7 PM)
 */
function getPendingWorkMessage(module, staff_name, student_name, pending_work = '') {
  const templates = moduleMessages[module] || genericPendingMessages;
  return getRandomMessage(templates, { name: staff_name, student_name, module, pending_work });
}

/**
 * Get random interval between 1-2 hours (in milliseconds)
 */
function getRandomInterval() {
  const hours = 1 + Math.random(); // 1 to 2 hours
  return hours * 60 * 60 * 1000;
}

/**
 * Get random offset for each staff to avoid same-time notifications (0-30 minutes)
 */
function getRandomStaffOffset(staff_id) {
  // Use staff_id to generate consistent but different offsets
  const hash = staff_id.split('').reduce((acc, char) => acc + char.charCodeAt(0), 0);
  const minutes = (hash % 31); // 0-30 minutes
  return minutes * 60 * 1000;
}

/**
 * Get next notification time for a specific staff member
 */
function getNextNotificationTime(staff_id, last_notification_time = null) {
  const now = new Date();
  const current_hour = now.getHours();
  
  // Only send between 10 AM - 7 PM
  if (current_hour < 10 || current_hour >= 19) {
    return null;
  }
  
  // If no previous notification, send after random offset
  if (!last_notification_time) {
    return new Date(now.getTime() + getRandomStaffOffset(staff_id));
  }
  
  // Calculate next notification time with random interval
  const next_time = new Date(last_notification_time.getTime() + getRandomInterval());
  
  // Make sure it's still within 10 AM - 7 PM window
  if (next_time.getHours() >= 19 || next_time.getHours() < 10) {
    return null;
  }
  
  return next_time;
}

/**
 * Check if notification should be sent now
 */
function shouldSendNotification(staff_id, last_notification_time = null) {
  const next_time = getNextNotificationTime(staff_id, last_notification_time);
  if (!next_time) return false;
  
  const now = new Date();
  return now >= next_time;
}

